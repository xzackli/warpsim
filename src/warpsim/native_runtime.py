"""Small pinned adapter for native C++/CUDA compilation and launch.

Warp supplies NVRTC, device allocations, streams and CUDA Graph ownership. The
executed source is ordinary C++/CUDA generated by the core compiler, not a Warp kernel
or expression interpreter. Private Warp entry points are isolated to this module.
"""

import ctypes
import hashlib
import os
from pathlib import Path
import platform
import subprocess
import tempfile
import threading
from time import perf_counter

import warp as wp

_lock = threading.RLock()
_cache = {}
POINTER = ctypes.c_void_p
INT = ctypes.c_int
LONG = ctypes.c_int64


class NativeModule:
    def __init__(self, source, device, mode="release", *, openmp=False):
        start = perf_counter()
        self.device = wp.get_device(device)
        self.mode = mode
        identity = f"{source}\n{mode}\n{platform.machine()}\n{wp.__version__}\n{self.device.arch if self.device.is_cuda else 'g++'}"
        if openmp:
            identity += "\nopenmp"
        digest = hashlib.sha256(identity.encode()).hexdigest()
        cache = (
            Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache"))
            / "warpsim-core"
            / "native"
        )
        cache.mkdir(parents=True, exist_ok=True)
        self.source_path = cache / f"{digest}.cpp"
        self.binary_path = (
            cache / f"{digest}{'.cubin' if self.device.is_cuda else '.so'}"
        )
        self.cache_hit = self.binary_path.exists()
        with _lock:
            if not self.binary_path.exists():
                with tempfile.TemporaryDirectory(
                    dir=cache, prefix="compile-"
                ) as temporary:
                    stage = Path(temporary)
                    cu = stage / "model.cu"
                    cu.write_text(source)
                    target = stage / self.binary_path.name
                    if self.device.is_cuda:
                        if wp.__version__ != "1.18.0":
                            raise RuntimeError(
                                "Native CUDA adapter is qualified for Warp 1.18.0"
                            )
                        from warp._src.build import build_cuda

                        build_cuda(
                            str(cu),
                            self.device.arch,
                            str(target),
                            pch_dir=None,
                            config=mode,
                            fast_math=False,
                            use_precompiled_headers=False,
                            lineinfo=True,
                        )
                    else:
                        flags = (
                            ["-O3"]
                            if mode == "release"
                            else [
                                "-O1",
                                "-g",
                                "-fsanitize=undefined",
                                "-fno-sanitize-recover=all",
                            ]
                        )
                        command = [
                            "g++",
                            "-x",
                            "c++",
                            *flags,
                            *(["-fopenmp"] if openmp else []),
                            "-std=c++17",
                            "-shared",
                            "-fPIC",
                            "-fno-exceptions",
                            "-fno-rtti",
                            str(cu),
                            "-o",
                            str(target),
                        ]
                        completed = subprocess.run(
                            command, capture_output=True, text=True, timeout=120
                        )
                        if completed.returncode:
                            raise RuntimeError(
                                f"Native model compilation failed:\n{completed.stderr}"
                            )
                    os.replace(cu, self.source_path)
                    os.replace(target, self.binary_path)
        self.compile_seconds = perf_counter() - start
        load_start = perf_counter()
        self._functions = {}
        if self.device.is_cuda:
            from warp._src.build import load_cuda
            from warp._src.context import runtime

            self._core = runtime.core
            self.handle = load_cuda(str(self.binary_path), self.device)
            if not self.handle:
                raise RuntimeError("CUDA could not load native model")
            self.advance = self._core.wp_cuda_get_kernel(
                self.device.context, self.handle, b"advance"
            )
            self.initialize = self._core.wp_cuda_get_kernel(
                self.device.context, self.handle, b"initialize"
            )
            if not self.advance or not self.initialize:
                raise RuntimeError("Native CUDA kernel symbols missing")
            properties = (ctypes.c_int * 2)()
            if not self._core.wp_cuda_get_kernel_properties(
                self.device.context, self.advance, properties, 2
            ):
                raise RuntimeError("CUDA could not query native kernel properties")
            self.kernel_properties = {
                "registers_per_thread": properties[0],
                "local_bytes_per_thread": properties[1],
            }
        else:
            self.handle = ctypes.CDLL(str(self.binary_path))
            self.advance = self.handle.advance
            self.advance.argtypes = [POINTER] * 4 + [INT, INT, LONG, INT, POINTER, INT]
            self.advance.restype = None
            self.initialize = self.handle.initialize
            self.initialize.argtypes = [POINTER, POINTER, INT]
            self.initialize.restype = None
            self.kernel_properties = {}
        self.compile_load_seconds = perf_counter() - start
        self.load_seconds = perf_counter() - load_start

    def function(self, name, argtypes=None):
        """Load an optional generated entry point from this native module."""
        if name not in self._functions:
            if self.device.is_cuda:
                function = self._core.wp_cuda_get_kernel(
                    self.device.context, self.handle, name.encode()
                )
                if not function:
                    raise RuntimeError(f"Native kernel symbol missing: {name}")
            else:
                function = getattr(self.handle, name)
                function.argtypes = argtypes
                function.restype = None
            self._functions[name] = function
        return self._functions[name]

    def __del__(self):
        # Captured graphs are owned by a session which also owns this module.
        # Evicting a cache entry therefore cannot unload an in-use kernel.
        try:
            handle = getattr(self, "handle", None)
            if handle:
                if self.device.is_cuda:
                    self._core.wp_cuda_unload_module(self.device.context, handle)
                else:
                    import _ctypes

                    _ctypes.dlclose(handle._handle)
                self.handle = None
        except Exception:
            pass  # Interpreter shutdown may already have released the CUDA context.

    def launch(self, function, parameters, n, block_size=128):
        if self.device.is_cuda:
            addresses = (ctypes.c_void_p * len(parameters))(
                *(ctypes.addressof(v) for v in parameters)
            )
            stream = wp.get_stream(self.device)
            error = self._core.wp_cuda_launch_kernel(
                self.device.context,
                function,
                n,
                0,
                block_size,
                0,
                1,
                0,
                addresses,
                stream.cuda_stream,
                None,
            )
            if error:
                raise RuntimeError(f"Native CUDA launch failed with code {error}")
        else:
            function(*parameters)


def compile_native(design, device, mode="release"):
    from .native_codegen import generate

    return compile_source(generate(design), device, mode)


def compile_source(source, device, mode="release", *, openmp=False):
    """Compile trusted generated source through the shared bounded module cache."""
    if mode not in ("release", "debug"):
        raise ValueError("Native mode must be release or debug")
    target = wp.get_device(device)
    key = (hashlib.sha256(source.encode()).digest(), target.alias, mode, openmp)
    with _lock:
        if key not in _cache:
            if len(_cache) >= 64:
                _cache.pop(next(iter(_cache)))
            _cache[key] = NativeModule(source, target, mode, openmp=openmp)
        return _cache[key]
